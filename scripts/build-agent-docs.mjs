#!/usr/bin/env node
// Writes dist/AGENTS.md and dist/docs/ — what a consuming app's coding agent
// reads to use the library as it is meant to be used (D-105).
//
//   dist/AGENTS.md              docs/for-agents.md, with a component index
//                               generated from each component doc's opening
//   dist/docs/RULES.md          docs/RULES.md
//   dist/docs/components/*.md   docs/components/*.md
//
// The docs are copied, not rewritten, except for their links: a link to a
// file that ships beside them stays relative, and a link to anything else in
// the repository (specs, the decision log) becomes a GitHub URL, so nothing
// an agent follows from inside node_modules is a dead end. Run by
// `npm run build`; `buildAgentDocs` is exported for the unit test.

import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, normalize, posix, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const REPO = 'https://github.com/mod-0-dev/pixel-perfect/blob/main';
const MARKER = '<!-- COMPONENT INDEX: generated by scripts/build-agent-docs.mjs from docs/components/*.md -->';

/** The doc's opening paragraph, up to its "Spec:" pointer, as one plain line. */
export function summaryOf(markdown) {
  const lines = markdown.split('\n');
  const start = lines.findIndex((line, i) => i > 0 && line.trim() !== '');
  const paragraph = [];
  for (let i = start; i < lines.length && lines[i].trim() !== ''; i += 1) paragraph.push(lines[i].trim());
  return paragraph
    .join(' ')
    .replace(/\s*Spec:.*$/, '')
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
    .trim();
}

/**
 * Re-point a doc's relative links: kept when the target ships too, a GitHub
 * URL when it does not. `from` is the doc's repo-relative path.
 */
export function rewriteLinks(markdown, from, shipped) {
  return markdown.replace(/\]\(([^)\s]+)\)/g, (match, href) => {
    if (/^[a-z]+:/i.test(href) || href.startsWith('#') || href.startsWith('/')) return match;
    const [path, anchor = ''] = href.split('#');
    const target = posix.normalize(posix.join(posix.dirname(from), path));
    if (shipped.has(target)) return match;
    return `](${REPO}/${target}${anchor ? `#${anchor}` : ''})`;
  });
}

export function buildAgentDocs(outDir = join(ROOT, 'dist')) {
  const componentFiles = readdirSync(join(ROOT, 'docs/components'))
    .filter((name) => name.endsWith('.md'))
    .sort();
  const shipped = new Set(['docs/RULES.md', ...componentFiles.map((name) => `docs/components/${name}`)]);

  mkdirSync(join(outDir, 'docs/components'), { recursive: true });
  for (const name of componentFiles) {
    const from = `docs/components/${name}`;
    writeFileSync(join(outDir, from), rewriteLinks(readFileSync(join(ROOT, from), 'utf8'), from, shipped));
  }
  writeFileSync(
    join(outDir, 'docs/RULES.md'),
    rewriteLinks(readFileSync(join(ROOT, 'docs/RULES.md'), 'utf8'), 'docs/RULES.md', shipped),
  );

  const index = componentFiles
    .map((name) => {
      const component = name.replace(/\.md$/, '');
      const summary = summaryOf(readFileSync(join(ROOT, 'docs/components', name), 'utf8'));
      return `- [\`${component}\`](docs/components/${name}) — ${summary}`;
    })
    .join('\n');

  const template = readFileSync(join(ROOT, 'docs/for-agents.md'), 'utf8');
  if (!template.includes(MARKER)) throw new Error(`docs/for-agents.md has lost its index marker: ${MARKER}`);
  const { version } = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));
  const agents = template
    .replace(MARKER, index)
    .replace('# pixel-perfect — for the coding agent in your app', `# pixel-perfect ${version} — for the coding agent in your app`);
  writeFileSync(join(outDir, 'AGENTS.md'), agents);

  return { files: componentFiles.length + 2, out: normalize(relative(ROOT, outDir)) || '.' };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === normalize(process.argv[1])) {
  const { files, out } = buildAgentDocs();
  console.log(`Wrote ${out}/AGENTS.md and ${files - 1} docs beside it`);
}
